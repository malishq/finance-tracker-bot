def categories_for(kind: str, custom: Iterable[Category] = ()) -> List[Category]:
    defaults = [c for c in DEFAULT_CATEGORIES if c.kind == kind]
    extra = [c for c in custom if c.kind == kind]
    fallback = [c for c in defaults if c.name == FALLBACK[kind]]
    main = [c for c in defaults if c.name != FALLBACK[kind]]
    return main + extra + fallback


def find_by_slug(slug: str, custom: Iterable[Category] = ()) -> Optional[Category]:
    for category in list(DEFAULT_CATEGORIES) + list(custom):
        if category.slug == slug:
            return category
    return None


def find_by_name(name: str, kind: str, custom: Iterable[Category] = ()) -> Optional[Category]:
    for category in list(DEFAULT_CATEGORIES) + list(custom):
        if category.kind == kind and category.name == name:
            return category
    return None


def emoji_for(name: str, kind: str, custom: Iterable[Category] = ()) -> str:
    category = find_by_name(name, kind, custom)
    return category.emoji if category else "📁"


def label_for(name: str, kind: str, custom: Iterable[Category] = ()) -> str:
    return f"{emoji_for(name, kind, custom)} {name}"
